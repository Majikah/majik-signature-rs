mod common;

use common::new_key;
use majik_signature::*;

#[test]
fn sign_and_verify_roundtrip() {
    let key = new_key("alice");
    let content = b"hello post-quantum world";
    let sig = MajikSignature::sign(content, &key, None).unwrap();
    let keys = MajikSignature::public_keys_from_majik_key(&key).unwrap();
    let res = MajikSignature::verify(content, &sig, &keys, None).unwrap();
    assert!(res.valid, "{:?}", res.reason);
    assert_eq!(res.signer_id.as_deref(), Some(key.fingerprint()));

    // Tampered content
    let bad = MajikSignature::verify(b"hello post-quantum worlD", &sig, &keys, None).unwrap();
    assert!(!bad.valid);

    // Serialization round trip
    let s = sig.serialize().unwrap();
    let back = MajikSignature::deserialize(&s).unwrap();
    assert_eq!(back, sig);
    assert!(MajikSignature::verify(content, &back, &keys, None).unwrap().valid);
}

#[test]
fn payload_is_byte_exact() {
    let p = build_signing_payload(&PayloadFields {
        signer_id: "fp",
        timestamp: "2026-01-01T00:00:00.000Z",
        content_hash: "h",
        content_type: None,
        allowlist_hash: None,
        valid_until: Some("2027-01-01T00:00:00.000Z"),
        version_chain_hash: None,
    });
    assert_eq!(
        String::from_utf8(p).unwrap(),
        "majik-signature-v1:{\"v\":1,\"id\":\"fp\",\"ts\":\"2026-01-01T00:00:00.000Z\",\"ct\":null,\"hash\":\"h\",\"vu\":\"2027-01-01T00:00:00.000Z\"}"
    );
}

// ── Cross-implementation vectors (generated by the TypeScript library) ───────

fn b64(s: &str) -> Vec<u8> {
    base64_to_bytes(s).unwrap()
}

#[test]
fn verifies_signature_produced_by_typescript() {
    let v: serde_json::Value = serde_json::from_str(include_str!("fixtures/ts_vector.json")).unwrap();
    let content = b64(v["content"].as_str().unwrap());
    let sig = MajikSignature::from_json_value(&v["sigJson"]).unwrap();
    let keys = MajikSignerPublicKeys {
        signer_id: v["signerId"].as_str().unwrap().to_string(),
        ed_public_key: b64(v["edPublicKey"].as_str().unwrap()),
        ml_dsa_public_key: b64(v["mlDsaPublicKey"].as_str().unwrap()),
    };
    let res = MajikSignature::verify(&content, &sig, &keys, None).unwrap();
    assert!(res.valid, "TS signature rejected by Rust: {:?}", res.reason);
    assert_eq!(sig.valid_until(), Some("2099-01-01T00:00:00.000Z"));
    assert_eq!(sig.content_type(), Some("text/plain"));
}

/// Writes a Rust-produced vector so the TS side can verify it (see interop/verify_rust.mjs).
#[test]
fn emit_rust_vector_for_typescript() {
    let key = new_key("rust-alice");
    let content = b"interop content from Rust";
    let sig = MajikSignature::sign(
        content,
        &key,
        Some(&SignOptions { content_type: Some("text/plain".into()), ..Default::default() }),
    )
    .unwrap();
    let keys = MajikSignature::public_keys_from_majik_key(&key).unwrap();
    let out = serde_json::json!({
        "content": bytes_to_base64(content),
        "sigJson": sig.to_json(),
        "edPublicKey": bytes_to_base64(&keys.ed_public_key),
        "mlDsaPublicKey": bytes_to_base64(&keys.ml_dsa_public_key),
        "signerId": keys.signer_id,
    });
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("target");
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("rust_vector.json"), out.to_string()).unwrap();
}
